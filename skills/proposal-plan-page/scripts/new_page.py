#!/usr/bin/env python3
"""Start a Growth10x plan page from the template, or make the client version of a finished draft.
Python 3 stdlib only.

Start a page (internal draft):
  python3 new_page.py --client "Acme Robotics" --accent "#2F80ED" --theme dark \
      --kind "Founder branding plan" --month "November 2026" --title "Acme founder brand plan" \
      --out ./proposals/acme-robotics/plans/founder-brand-internal.html [--white-label]

Make the client version (removes every <!-- INT --> ... <!-- /INT --> block):
  python3 new_page.py --strip-internal ./plans/founder-brand-internal.html --out ./plans/founder-brand-client.html

Print the accent tokens only (with contrast ratios):
  python3 new_page.py --accent "#2F80ED" --tokens
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(os.path.dirname(HERE), 'assets', 'plan-page-template.html')

INK, DARK_BG, LIGHT_BG, WHITE = (23, 22, 29), (23, 22, 29), (250, 249, 245), (255, 255, 255)
DARK_GLASS = (29, 28, 36)      # glass panel over the dark ground, for the text contrast target


def hex2rgb(h):
    h = h.strip().lstrip('#')
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    if not re.fullmatch(r'[0-9a-fA-F]{6}', h):
        sys.exit('Accent must be a hex colour like #2F80ED, got %r' % h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb2hex(c):
    return '#%02X%02X%02X' % tuple(max(0, min(255, round(v))) for v in c)


def lum(c):
    def ch(v):
        v /= 255.0
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def toward(c, ground, target, to):
    for k in range(0, 101):
        m = mix(c, to, k / 100.0)
        if contrast(m, ground) >= target:
            return m
    return to


def accent_tokens(hexacc):
    """Same rules as the proposal deck, so deck and plan pages match: the fill stays the client colour
    unless it nearly disappears on the ground; text in the accent is shifted until it reaches 4.5:1."""
    acc = hex2rgb(hexacc)
    out = {}
    for theme, ground, glass in (('dark', DARK_BG, DARK_GLASS), ('light', LIGHT_BG, WHITE)):
        fill = acc
        if theme == 'light' and contrast(acc, ground) < 2.2:
            fill = toward(acc, ground, 2.2, INK)
        if theme == 'dark' and contrast(acc, ground) < 2.2:
            fill = toward(acc, ground, 2.2, WHITE)
        on = WHITE if contrast(fill, WHITE) >= contrast(fill, INK) else INK
        to = WHITE if theme == 'dark' else INK
        tx = toward(fill, ground, 4.6, to)
        tx = toward(tx, glass, 4.6, to)
        out[theme] = {
            '--acc': rgb2hex(fill), '--acc-rgb': '%d,%d,%d' % tuple(round(v) for v in fill),
            '--on-acc': rgb2hex(on), '--acc-tx': rgb2hex(tx),
            '_ratios': 'fill vs ground %.2f, accent text vs ground %.2f, text on fill %.2f' % (
                contrast(fill, ground), contrast(tx, ground), contrast(on, fill)),
        }
    return out


def accent_css(hexacc):
    t = accent_tokens(hexacc)
    def decl(d):
        return ';'.join('%s:%s' % (k, v) for k, v in d.items() if not k.startswith('_'))
    return ('/* ACCENT:start (generated by new_page.py from the client colour %s) */\n'
            ':root{%s}\nhtml[data-theme="light"]{%s}\n/* ACCENT:end */' % (hexacc.upper(), decl(t['dark']), decl(t['light']))), t


def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def strip_internal(html):
    out, n = re.subn(r'\s*<!-- INT -->.*?<!-- /INT -->', '', html, flags=re.S)
    if '<!-- INT' in out or '<!-- /INT' in out:
        sys.exit('Unbalanced INT markers: every <!-- INT --> needs a matching <!-- /INT -->.')
    left = re.findall(r'class="[^"]*\bint\b[^"]*"', out)
    if left:
        sys.exit('Found %d class="int" blocks outside INT markers. Wrap them in <!-- INT --> ... <!-- /INT -->.' % len(left))
    return out, n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--client'); ap.add_argument('--accent'); ap.add_argument('--theme', choices=['dark', 'light'])
    ap.add_argument('--kind', default='Plan'); ap.add_argument('--month'); ap.add_argument('--title')
    ap.add_argument('--white-label', action='store_true'); ap.add_argument('--out')
    ap.add_argument('--strip-internal', metavar='DRAFT_HTML'); ap.add_argument('--tokens', action='store_true')
    ap.add_argument('--template', default=TEMPLATE)
    a = ap.parse_args()

    if a.tokens:
        if not a.accent:
            sys.exit('--tokens needs --accent')
        css, t = accent_css(a.accent)
        print(css)
        for th in ('dark', 'light'):
            print('/* %s: %s */' % (th, t[th]['_ratios']))
        return

    if a.strip_internal:
        if not a.out:
            sys.exit('--strip-internal needs --out')
        html, n = strip_internal(open(a.strip_internal, encoding='utf-8').read())
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        open(a.out, 'w', encoding='utf-8').write(html)
        print('Client version written: %s (%d internal blocks removed)' % (a.out, n))
        return

    missing = [k for k in ('client', 'accent', 'theme', 'month', 'title', 'out') if not getattr(a, k)]
    if missing:
        sys.exit('Missing: ' + ', '.join('--' + m for m in missing))
    html = open(a.template, encoding='utf-8').read()
    css, t = accent_css(a.accent)
    html, n = re.subn(r'/\* ACCENT:start.*?/\* ACCENT:end \*/', lambda m: css, html, flags=re.S)
    if n != 1:
        sys.exit('Template has no ACCENT block')
    rep = {'{{CLIENT}}': esc(a.client), '{{KIND}}': esc(a.kind), '{{MONTH}}': esc(a.month), '{{TITLE}}': esc(a.title),
           '{{THEME}}': a.theme, '{{BRAND_CLASS}}': 'wl' if a.white_label else ''}
    for k, v in rep.items():
        html = html.replace(k, v)
    html = html.replace(' class=""', '')
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, 'w', encoding='utf-8').write(html)
    print('Page written: %s' % a.out)
    for th in ('dark', 'light'):
        print('  accent %s: %s' % (th, t[th]['_ratios']))


if __name__ == '__main__':
    main()
